"""Deterministic fake AI for tests and `AI_MODE=fake` (no API keys, no cost).

FakeEmbedder uses the hashing trick over word tokens, so texts sharing words get
similar vectors — good enough to exercise real hybrid search end to end.
"""

from __future__ import annotations

import hashlib
import json
import math
import re
from collections.abc import AsyncIterator
from typing import Any, Literal

from docify.ai.llm import LLMResult, Task, Usage

_WORD = re.compile(r"[A-Za-z][A-Za-z0-9]+")
_PATH_HINT = re.compile(r'path="([^"]+)" lines="(\d+)-(\d+)"')
_FILE_HINT = re.compile(r"^### (\S+)", re.M)


def _tokens(text: str) -> list[str]:
    from docify.ai.chunking import split_identifiers

    return [w.lower() for w in _WORD.findall(split_identifiers(text))]


class FakeEmbedder:
    model = "fake-embed"

    def __init__(self, dim: int = 1024) -> None:
        self.dim = dim

    def _vec(self, text: str) -> list[float]:
        v = [0.0] * self.dim
        for tok in _tokens(text):
            h = int.from_bytes(hashlib.blake2b(tok.encode(), digest_size=8).digest(), "big")
            v[h % self.dim] += 1.0 if (h >> 32) & 1 else -1.0
        norm = math.sqrt(sum(x * x for x in v)) or 1.0
        return [x / norm for x in v]

    async def embed(self, texts: list[str], *, input_type: Literal["document", "query"]) -> tuple[
        list[list[float]], int]:
        return [self._vec(t) for t in texts], sum(len(t) // 4 for t in texts)


class FakeLLM:
    """Echo-style fake: produces plausible, schema-valid output derived from the prompt."""

    def __init__(self) -> None:
        self.calls: list[dict[str, Any]] = []

    @staticmethod
    def _prompt_text(messages: list[dict[str, Any]]) -> str:
        parts = []
        for m in messages:
            c = m.get("content")
            if isinstance(c, str):
                parts.append(c)
            elif isinstance(c, list):
                parts.extend(b.get("text", "") for b in c if isinstance(b, dict))
        return "\n".join(parts)

    def _usage(self, prompt: str, out: str) -> Usage:
        return Usage(input_tokens=len(prompt) // 4 + 50, output_tokens=len(out) // 4 + 5)

    async def complete(self, *, task: Task, model: str, system: str, messages: list[dict[str, Any]],
                       max_tokens: int, output_schema: dict[str, Any] | None = None) -> LLMResult:
        prompt = self._prompt_text(messages)
        self.calls.append({"task": task, "model": model, "prompt_chars": len(prompt)})
        data: dict[str, Any] | None = None
        if task == "summary":
            path = (re.search(r"^Path: (.+)$", prompt, re.M) or [None, "file"])[1]
            symbols = sorted(set(re.findall(r"(?:def|class|function|func)\s+([A-Za-z_][A-Za-z0-9_]*)", prompt)))[:20]
            data = {"summary": f"Fake summary of {path}. It defines {', '.join(symbols) or 'no public symbols'}.",
                    "symbols": symbols}
            text = json.dumps(data)
        elif task == "changelog":
            text = "- Fake changelog entry: updated " + ", ".join(sorted(set(_FILE_HINT.findall(prompt)))[:5])
        else:  # doc
            files = _FILE_HINT.findall(prompt)
            cite = f" [[{files[0]}:1-1]]" if files else ""
            title = (re.search(r"^Document: (.+)$", prompt, re.M) or [None, "Documentation"])[1]
            text = (f"# {title}\n\nThis is generated by the fake AI (AI_MODE=fake).{cite}\n\n"
                    "## Files\n\n" + "\n".join(f"- `{f}`" for f in files[:20]) + "\n")
        return LLMResult(text=text, data=data, stop_reason="end_turn", model=model, usage=self._usage(prompt, text))

    async def stream(self, *, task: Task, model: str, system: str, messages: list[dict[str, Any]],
                     max_tokens: int, usage_out: Usage) -> AsyncIterator[str]:
        prompt = self._prompt_text(messages)
        self.calls.append({"task": task, "model": model, "prompt_chars": len(prompt)})
        hits = _PATH_HINT.findall(prompt)
        if hits:
            path, a, b = hits[0]
            answer = f"Based on the code, the relevant logic is in `{path}` (lines {a}-{b}) [1]."
        else:
            answer = "I don't know based on the indexed code."
        for word in answer.split(" "):
            yield word + " "
        u = self._usage(prompt, answer)
        usage_out.input_tokens, usage_out.output_tokens = u.input_tokens, u.output_tokens
